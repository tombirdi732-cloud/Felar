const CHAPTER_SCREENS = { 1: CH1_SCREENS, 2: CH2_SCREENS, 3: CH3_SCREENS };

// ============================================================
// Сборка уровня: экраны -> сетка тайлов + список спавнов
// ============================================================
class Level {
  constructor(ch) {
    this.ch = ch;
    this.meta = CHAPTER_META[ch];
    const screens = CHAPTER_SCREENS[ch];
    this.cols = screens.length * SCREEN_COLS;
    this.rows = ROWS;
    this.pw = this.cols * TILE;   // ширина в пикселях
    this.phh = this.rows * TILE;
    this.grid = [];
    this.spawns = [];
    for (let r = 0; r < ROWS; r++) {
      let row = "";
      for (const s of screens) row += (s[r] || "").padEnd(SCREEN_COLS).slice(0, SCREEN_COLS);
      this.grid.push(row.split(""));
    }
    // извлекаем сущности из сетки
    for (let r = 0; r < ROWS; r++) {
      for (let c = 0; c < this.cols; c++) {
        const ch2 = this.grid[r][c];
        if (" #=^v".includes(ch2)) continue;
        this.spawns.push({ char: ch2, col: c, row: r, x: c * TILE, y: r * TILE });
        this.grid[r][c] = " ";
      }
    }
  }

  tile(c, r) {
    if (c < 0 || c >= this.cols) return "#"; // стены по краям
    if (r < 0 || r >= this.rows) return " ";
    return this.grid[r][c];
  }
  solidAtPx(px, py) {
    return this.tile(Math.floor(px / TILE), Math.floor(py / TILE)) === "#";
  }
  onewayAtPx(px, py) {
    return this.tile(Math.floor(px / TILE), Math.floor(py / TILE)) === "=";
  }
  // твёрдые тайлы рядом с прямоугольником
  solidsNear(rect) {
    const out = [];
    const c0 = Math.floor(rect.x / TILE) - 1, c1 = Math.floor((rect.x + rect.w) / TILE) + 1;
    const r0 = Math.floor(rect.y / TILE) - 1, r1 = Math.floor((rect.y + rect.h) / TILE) + 1;
    for (let r = r0; r <= r1; r++)
      for (let c = c0; c <= c1; c++)
        if (this.tile(c, r) === "#")
          out.push({ x: c * TILE, y: r * TILE, w: TILE, h: TILE });
    return out;
  }
  onewaysNear(rect) {
    const out = [];
    const c0 = Math.floor(rect.x / TILE) - 1, c1 = Math.floor((rect.x + rect.w) / TILE) + 1;
    const r0 = Math.floor(rect.y / TILE) - 1, r1 = Math.floor((rect.y + rect.h) / TILE) + 1;
    for (let r = r0; r <= r1; r++)
      for (let c = c0; c <= c1; c++)
        if (this.tile(c, r) === "=")
          out.push({ x: c * TILE, y: r * TILE, w: TILE, h: TILE });
    return out;
  }
  // хитбоксы шипов, пересекающие прямоугольник
  spikesHit(rect) {
    const c0 = Math.floor(rect.x / TILE), c1 = Math.floor((rect.x + rect.w) / TILE);
    const r0 = Math.floor(rect.y / TILE), r1 = Math.floor((rect.y + rect.h) / TILE);
    for (let r = r0; r <= r1; r++)
      for (let c = c0; c <= c1; c++) {
        const t = this.tile(c, r);
        if (t === "^") {
          const hb = { x: c * TILE + 5, y: r * TILE + 14, w: TILE - 10, h: TILE - 14 };
          if (aabb(rect, hb)) return true;
        } else if (t === "v") {
          const hb = { x: c * TILE + 5, y: r * TILE, w: TILE - 10, h: TILE - 14 };
          if (aabb(rect, hb)) return true;
        }
      }
    return false;
  }
}
