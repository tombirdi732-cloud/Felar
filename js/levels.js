/* ---------- Билдер ---------- */
const _M = n => MANIFEST_DATA[n];
const _W = n => _M(n).w;

/* parts: [спрайт, зазорОтКраяПредыдущего, сдвигВысоты, 'solid'|'one'] */
function chain(startX, surfY, parts) {
  let x = startX, y = surfY;
  const list = [];
  for (const [s, gap, dy = 0, mode = 'solid'] of parts) {
    y += dy;
    const w = _W(s);
    list.push([s, Math.round(x + gap + w / 2), y, mode]);
    x += gap + w;
  }
  return {
    list,
    endX: x,
    /* точка на острове i: f — доля ширины (0..1), возвращает [x, surfY] */
    at(i, f = 0.5) {
      const [s, cx, sy] = list[i];
      const w = _W(s);
      return [Math.round(cx + (f - 0.5) * w * 0.8), sy];
    },
  };
}

/* Авторасстановка декораций по островам — ничего не висит в воздухе */
function dress(ch, seed) {
  const decos = [], aplants = [], vines = [];
  const smallD = ['deco9', 'deco10', 'deco18', 'deco19', 'deco22', 'deco28', 'hill0', 'hill4'];
  const smallA = ['aplant1', 'aplant2', 'aplant3', 'aplant5', 'aplant7', 'awind1'];
  const vs = ['vine1', 'vine2', 'vine3', 'vine4'];
  const rnd = () => (seed = (seed * 16807) % 2147483647) / 2147483647;
  ch.list.forEach(([s, cx, sy, mode]) => {
    const w = _W(s), h = _M(s).h;
    if (w >= 280) {
      const n = 1 + ((rnd() * 2) | 0);
      for (let k = 0; k < n; k++) {
        const x = Math.round(cx + (rnd() - 0.5) * w * 0.55);
        if (rnd() < 0.5) aplants.push([smallA[(rnd() * smallA.length) | 0], x, sy + 2]);
        else decos.push([smallD[(rnd() * smallD.length) | 0], x, sy + 2]);
      }
    }
    if (w >= 300 && rnd() < 0.75) {
      vines.push([vs[(rnd() * vs.length) | 0], Math.round(cx + (rnd() - 0.5) * w * 0.4), sy + (mode === 'one' ? h * 0.5 : 44)]);
    }
  });
  return { decos, aplants, vines };
}

